"""Run memo-design-smoke.py first to prepare the isolated host; never contacts native data."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

out=Path('test-artifacts/unified-memo');out.mkdir(parents=True,exist_ok=True)
results=[]
with sync_playwright() as p:
    browser=p.chromium.launch()
    for width in [900,420]:
        ctx=browser.new_context(viewport={'width':width,'height':720})
        ctx.route('http://127.0.0.1:39393/**',lambda route:route.abort())
        ctx.add_init_script("""if(!localStorage.getItem('daybridge.memo.preview.sessions.v2'))localStorage.setItem('daybridge.memo.preview.sessions.v2',JSON.stringify({schemaVersion:2,active:null,lastClosed:null,archives:[{id:'old-note',text:'이전 메모\\n기존 보관함 내용',revision:1,createdAtUnixMs:1,updatedAtUnixMs:1}]}));""")
        page=ctx.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto('http://127.0.0.1:5187/test-artifacts/memo-design.html?panel=1&compose=1')
        editor=page.get_by_role('textbox',name='메모 내용')
        expect(editor).to_be_focused();expect(editor).to_have_value('')
        editor.fill('회의에서 떠오른 생각\n한글 메모를 바로 적습니다.\n마지막 글자까지 보관')
        expect(page.locator('.memo-compose').get_by_role('status')).to_have_text('자동 저장됨')
        page.screenshot(path=str(out/f'compose-{width}.png'))
        if width<560:page.get_by_role('button',name='목록으로',exact=True).click()
        page.get_by_role('button',name='이전 메모',exact=True).click()
        expect(page.locator('pre')).to_contain_text('기존 보관함 내용')
        assert page.evaluate("JSON.parse(localStorage.getItem('daybridge.memo.preview.sessions.v2')).active.text").startswith('회의에서')
        if width<560:page.get_by_role('button',name='목록으로',exact=True).click()
        page.get_by_role('button',name='＋ 새 메모',exact=True).click()
        expect(editor).to_have_value('');expect(editor).to_be_focused()
        assert any(x['text'].startswith('회의에서') for x in page.evaluate("JSON.parse(localStorage.getItem('daybridge.memo.preview.sessions.v2')).archives"))
        editor.fill('새 창에서 쓴 두 번째 메모')
        editor.dispatch_event('compositionstart')
        editor.press('Escape')
        assert not page.evaluate('fixture.closed')
        editor.dispatch_event('compositionend',{'data':'메모'})
        editor.press('Escape');page.wait_for_function('fixture.closed')
        state=page.evaluate("JSON.parse(localStorage.getItem('daybridge.memo.preview.sessions.v2'))")
        assert state['active'] is None and any(x['text']=='새 창에서 쓴 두 번째 메모' for x in state['archives'])
        page.reload();expect(editor).to_be_focused();expect(editor).to_have_value('')
        page.evaluate("()=>{window.originalMemoWrite=Storage.prototype.setItem;Storage.prototype.setItem=function(){throw Error('fixture_disk_failure');};}")
        editor.fill('실패해도 남아 있어야 할 메모')
        page.get_by_role('button',name='메모 보관함 닫기',exact=True).click()
        expect(editor).to_have_value('실패해도 남아 있어야 할 메모')
        assert not page.evaluate('fixture.closed')
        expect(page.locator('.memo-compose').get_by_role('alert')).to_be_visible()
        page.screenshot(path=str(out/f'failure-{width}.png'))
        page.evaluate('()=>{Storage.prototype.setItem=window.originalMemoWrite;}')
        page.get_by_role('button',name='메모 보관함 닫기',exact=True).click()
        page.wait_for_function('fixture.closed')
        page.reload();expect(editor).to_have_value('');expect(editor).to_be_focused()
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        assert not errors,errors
        results.append({'width':width,'focus':True,'autosave':True,'browseKeepsDraft':True,'newArchivesPrior':True,'closeArchives':True,'reopenBlank':True,'failurePreserved':True,'pageErrors':0})
        ctx.close()
    browser.close()
(out/'result.json').write_text(json.dumps({'passed':True,'nativeVerified':False,'scenarios':results},ensure_ascii=False,indent=2),encoding='utf-8')
print('Unified memo browser checks: 2 layouts passed')
